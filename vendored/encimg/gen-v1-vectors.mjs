// Independent generator for vendored/encimg/v1-vectors.json (SUR-1259, ADR 0008). Written from the
// ADR's §Wire format with node:crypto only — NOT from the Rust code — so the Rust seal reproducing
// these bytes is a cross-implementation check, not a self-check. Kept for provenance: re-running it
// must reproduce the frozen file byte for byte.
//
//   node vendored/encimg/gen-v1-vectors.mjs > vendored/encimg/v1-vectors.json
import { createCipheriv, createHash, hkdfSync } from 'node:crypto';

const CHUNK = 262144;
const MAGIC = Buffer.from('encimg:v1', 'ascii');
const hex = (b) => Buffer.from(b).toString('hex');
const seq = (n, start) => Buffer.from(Array.from({ length: n }, (_, i) => (start + i) & 0xff));
const gen = (n) => Buffer.from(Array.from({ length: n }, (_, i) => i % 251));

const mk = Buffer.alloc(32, 0x11);
const kWrap = Buffer.from(hkdfSync('sha256', mk, Buffer.alloc(32), Buffer.from('braird-image-key-wrap-v1'), 32));
const userId = '3f2b8c1e-9d4a-4e6f-8b7c-0a1d2e3f4a5b';
const dek = seq(32, 0x00);
const wrapIv = seq(12, 0xa0);
const rewrapIv = seq(12, 0xc0);
const prefix = seq(7, 0xb0);

function aad(uid, imageId) {
  const u = Buffer.from(uid, 'utf8');
  const i = Buffer.from(imageId, 'utf8');
  const len = (b) => Buffer.from([b.length >> 8, b.length & 0xff]);
  return Buffer.concat([MAGIC, len(u), u, len(i), i]);
}

function gcm(key, iv, pt, a) {
  const c = createCipheriv('aes-256-gcm', key, iv);
  c.setAAD(a);
  return Buffer.concat([c.update(pt), c.final(), c.getAuthTag()]);
}

function seal(path, pt, wIv = wrapIv) {
  const m = path.match(/^([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\/([A-Za-z0-9-]{1,64})\.jpg$/);
  if (!m || m[1] !== userId) throw new Error(`bad path ${path}`);
  const a = aad(m[1], m[2]);
  const parts = [MAGIC, wIv, gcm(kWrap, wIv, dek, a), prefix];
  const chunks = Math.max(1, Math.ceil(pt.length / CHUNK));
  for (let i = 0; i < chunks; i++) {
    const nonce = Buffer.concat([prefix, Buffer.from([i >>> 24, (i >>> 16) & 0xff, (i >>> 8) & 0xff, i & 0xff]), Buffer.from([i === chunks - 1 ? 1 : 0])]);
    parts.push(gcm(dek, nonce, pt.subarray(i * CHUNK, Math.min((i + 1) * CHUNK, pt.length)), a));
  }
  return Buffer.concat(parts);
}

const p = (stem) => `${userId}/${stem}.jpg`;
const small = [
  ['empty', p('note-empty'), 0],
  ['one-byte', p('note-one'), 1],
  ['small', p('note-small'), 37],
  ['pwa-id', p('k3x9a0bq'), 37],
  ['uuid-id', p('9c1d4e2f-6a7b-4c8d-9e0f-1a2b3c4d5e6f'), 37],
];
const large = [
  ['chunk-minus-1', p('note-chunk-minus-1'), CHUNK - 1],
  ['chunk', p('note-chunk'), CHUNK],
  ['chunk-plus-1', p('note-chunk-plus-1'), CHUNK + 1],
  ['two-chunks', p('note-two-chunks'), 2 * CHUNK],
];

const cases = [];
for (const [name, path, len] of small) cases.push({ name, path, len, sealed: hex(seal(path, gen(len))) });
cases.push({ name: 'rewrap', path: p('note-small'), len: 37, wrap_iv: hex(rewrapIv), sealed: hex(seal(p('note-small'), gen(37), rewrapIv)) });
for (const [name, path, len] of large) {
  const s = seal(path, gen(len));
  cases.push({ name, path, len, sealed_len: s.length, sealed_sha256: createHash('sha256').update(s).digest('hex') });
}

console.log(JSON.stringify({
  _note: 'encimg:v1 frozen vectors (SUR-1259, ADR 0008). Generated by vendored/encimg/gen-v1-vectors.mjs, an independent node:crypto implementation written from the ADR text, and reproduced byte for byte by the Rust seal (src/image_encryption.rs tests). Every case uses the same fixed data key, wrap IV and nonce prefix: fine for vectors, never for real seals (a DEK seals one image). Plaintext of length len: byte i = i % 251. Large cases pin the sealed bytes by length + SHA-256; small cases inline them. `rewrap` is `small` with a second wrap IV: the chunks are byte-identical, so an in-place re-wrap opens.',
  mk: hex(mk),
  k_wrap: hex(kWrap),
  user_id: userId,
  chunk: CHUNK,
  dek: hex(dek),
  wrap_iv: hex(wrapIv),
  nonce_prefix: hex(prefix),
  cases,
}, null, 2));
